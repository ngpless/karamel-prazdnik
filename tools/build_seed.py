def parse_articles(path):
    text = open(path, encoding='utf-8').read().replace('\r\n', '\n')
    items = []
    for chunk in re.split(r'^@@ ', text, flags=re.M)[1:]:
        head, body = chunk.split('\n', 1)
        slug, title, summary = [x.strip() for x in head.split('|', 2)]
        items.append((slug, title, summary, body.strip()))
    return items


def php_hash(password):
    out = subprocess.run(['php', '-r', 'echo password_hash($argv[1], PASSWORD_DEFAULT);', password],
                         capture_output=True, text=True, encoding='utf-8')
    if out.returncode != 0 or not out.stdout.startswith('$'):
        sys.exit('Не удалось получить хеш пароля через PHP: ' + out.stderr)
    return out.stdout.strip()


